export function getAge(id: AgeId): AgeDef {
  return AGES[id];
}

/** Landmarks a faction can build to advance INTO `age`. */
export function landmarksFor(factionId: string, age: AgeId): LandmarkDef[] {
  return LANDMARKS.filter((l) => l.factionId === factionId && l.age === age);
}

/** The age after `age`, or null at the last age. */
export function nextAge(age: AgeId): AgeId | null {
  const i = AGE_ORDER.indexOf(age);
  return i >= 0 && i < AGE_ORDER.length - 1 ? (AGE_ORDER[i + 1] as AgeId) : null;
}
