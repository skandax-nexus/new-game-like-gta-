export interface RealmRow {
  day: number;
  factionId: FactionId;
  alive: boolean;
  settlements: number;
  population: number;
  soldiers: number;
  treasury: number;
  foodReserve: number;
  age: string;
  wars: FactionId[];
}

export interface AiYear {
  seed: number;
  days: number;
  seconds: number;
  audit: CampaignAudit;
  journal: AiJournalEntry[];
  rows: RealmRow[];
  world: WorldState;
  markdown: string;
  saveText: string;
  saveIndex: Record<string, { meta: SaveGame['meta']; sizeBytes: number }>;
}

function realmRows(w: WorldState): RealmRow[] {
  const day = totalDays(w.calendar);
  return Object.keys(w.factions)
    .sort()
    .map((fid) => {
      const f = w.factions[fid]!;
      const owned = Object.values(w.settlements).filter((s) => s.ownerFactionId === fid);
      let soldiers = 0;
      for (const a of Object.values(w.armies)) if (a.factionId === fid) soldiers += armySoldiers(a);
      for (const s of owned) for (const u of s.garrison) soldiers += u.soldiers;
      const wars = Object.values(w.diplomacy.relations)
        .filter((r) => r.atWar && (r.a === fid || r.b === fid))
        .map((r) => (r.a === fid ? r.b : r.a))
        .sort();
      return { day, factionId: fid, alive: f.alive, settlements: owned.length, population: Math.round(owned.reduce((n, s) => n + s.population, 0)), soldiers, treasury: Math.round(f.treasury), foodReserve: Math.round(f.foodReserve), age: f.age, wars };
    });
}

const name = (fid: string): string => FACTIONS[fid]?.shortName ?? fid;

function narrative(y: Omit<AiYear, 'markdown' | 'saveText' | 'saveIndex'>): string {
  const L: string[] = [];
  const { audit, journal, rows } = y;
  L.push(`# SIM-02 - an AI-only sandbox year (seed ${y.seed})`);
  L.push('');
  L.push(`Generated by \`node scripts/sim-ai/autoplay.mjs\` (${y.days} days, ${y.seconds.toFixed(0)} s). OWNER: AI Engineer - Battle AI, Intents & Campaign AI (SIM-02).`);
  L.push('');
  L.push('Every realm of a six-realm sandbox (Normal difficulty, the default sliders) is run by the campaign AI - the nominal player realm included - through the same StrategicCommands a player issues. Battles autoresolve with the SIM-02 battle AI on both sides. Everything below is read from the AI decision journal (`aiJournal()`, `src/sim/strategic/ai/core.ts`) and the world events; the audit is the one `tests/sim/ai/campaign.test.ts` applies.');
  L.push('');
  L.push('## The realms');
  L.push('');
  L.push('| Realm | Personality | War ratio | Peace below | Weights (expand / defend / develop / diplomacy / raid / trade) |');
  L.push('|---|---|---|---|---|');
  for (const fid of Object.keys(y.world.factions).sort()) {
    const p = AI_PERSONALITY_DEFS[y.world.factions[fid]!.ai.personality]!;
    const w = p.weights;
    L.push(`| ${name(fid)} | ${p.name} | ${p.warRatio} | ${p.peaceWarScore} | ${w.expand} / ${w.defend} / ${w.develop} / ${w.diplomacy} / ${w.raid} / ${w.trade} |`);
  }
  L.push('');
  const landless = Object.keys(y.world.factions).sort().filter((fid) => rows.every((r) => r.factionId !== fid || r.settlements === 0));
  if (landless.length) L.push(`${landless.map(name).join(' and ')} hold no settlement on this map (the sandbox region has four realms and two free towns); they stay in the diplomatic picture only.`);
  L.push('');
  L.push('## Quarter by quarter');
  L.push('');
  L.push('| Day | Realm | Settlements | People | Soldiers | Treasury | Royal grain | Age | At war with |');
  L.push('|---|---|---|---|---|---|---|---|---|');
  for (const r of rows) {
    if (r.settlements === 0 && r.soldiers === 0) continue;
    L.push(`| ${r.day} | ${name(r.factionId)}${r.alive ? '' : ' (fallen)'} | ${r.settlements} | ${r.population} | ${r.soldiers} | ${r.treasury} | ${r.foodReserve} | ${r.age} | ${r.wars.map(name).join(', ') || '-'} |`);
  }
  L.push('');
  L.push('## The year in decisions');
  L.push('');
  const keyKinds = new Set(['war', 'peace', 'age', 'rebels']);
  const byDay = new Map<number, string[]>();
  const push = (d: number, t: string): void => {
    const a = byDay.get(d) ?? [];
    a.push(t);
    byDay.set(d, a);
  };
  for (const e of journal) {
    if (keyKinds.has(e.kind)) push(e.day, `**${name(e.factionId)}** ${e.text}`);
  }
  // First decision of each other kind per realm, and the economy's big calls.
  const seen = new Set<string>();
  for (const e of journal) {
    if (keyKinds.has(e.kind)) continue;
    const big = e.kind === 'economy' && (e.text.startsWith('orders rationing') || e.text.startsWith('tax policy') || e.text.startsWith('buys') || e.text.startsWith('sells'));
    const army = e.kind === 'army' && (e.text.includes('besiege') || e.text.includes('storms') || e.text.includes('lifts'));
    const key = `${e.factionId}|${e.kind}`;
    if (big || army || !seen.has(key)) {
      seen.add(key);
      push(e.day, `${name(e.factionId)} ${e.text}`);
    }
  }
  for (const c of audit.captures) push(c.day, `*${y.world.settlements[c.settlementId]?.name ?? c.settlementId} passes from ${c.from ? name(c.from) : 'its own people'} to ${name(c.to)}.*`);
  for (const p of audit.peaceMade) push(p.day, `*Peace between ${name(p.a)} and ${name(p.b)}.*`);
  for (const a of audit.ageUps) push(a.day, `*${name(a.factionId)} enters the ${a.age} age.*`);
  for (const d of [...byDay.keys()].sort((a, b) => a - b)) for (const t of byDay.get(d)!) L.push(`- Day ${d}: ${t}`);
  L.push('');
  L.push('## Decisions by kind');
  L.push('');
  const kinds = ['goal', 'war', 'peace', 'diplomacy', 'economy', 'build', 'recruit', 'age', 'army', 'spy', 'rebels'];
  L.push(`| Realm | ${kinds.join(' | ')} |`);
  L.push(`|---|${kinds.map(() => '---').join('|')}|`);
  for (const fid of Object.keys(y.world.factions).sort()) {
    const counts = kinds.map((k) => journal.filter((e) => e.factionId === fid && e.kind === k).length);
    if (counts.every((c) => c === 0)) continue;
    L.push(`| ${name(fid)} | ${counts.join(' | ')} |`);
  }
  L.push('');
  L.push('## Audit (the campaign test\'s checks on this run)');
  L.push('');
  const worstDebt = Math.max(0, ...Object.values(audit.worstDebtStreak));
  L.push(`- Longest run of days with a treasury below zero, any realm: **${worstDebt}** (limit 60).`);
  const aiWars = audit.wars.filter((w) => w.byAi);
  L.push(`- War declarations: ${audit.wars.length} (${aiWars.length} by an AI decision). Each AI declaration with the rule evaluated independently the hour before:`);
  for (const w of audit.wars) L.push(`  - day ${w.day}: ${name(w.a)} -> ${name(w.b)}: ${w.byAi ? `ratio ${w.ratio.toFixed(2)} vs threshold ${w.threshold.toFixed(2)}${w.blockedBefore ? `, BLOCKED (${w.blockedBefore})` : ''}` : w.other}`);
  const spells = audit.peace.filter((p) => p.belowSince <= y.days - 31);
  const late = spells.filter((p) => p.sued === null || p.sued - p.belowSince > 31);
  L.push(`- Peace: ${spells.length} spells of a war score below the realm's peaceWarScore; sued within 31 days in ${spells.length - late.length}.`);
  L.push(`- Ages: ${audit.ageUps.length ? audit.ageUps.map((a) => `${name(a.factionId)} -> ${a.age} (day ${a.day})`).join(', ') : 'none this year (requirements not met)'}; landmarks begun: ${audit.landmarkStarts.map((l) => `${name(l.factionId)} ${l.landmarkId} (day ${l.day})`).join(', ') || 'none'}; longest wait with the requirements met and no landmark: ${Math.max(0, ...Object.values(audit.worstReadyStreak))} days.`);
  L.push('');
  return `${L.join('\n')}\n`;
}

/** Run an AI-only sandbox for `days` and build the narrative and the end-of-year save. */
export function runAiYear(seed: number, days = 360): AiYear {
  resetAiJournal(true, 50_000);
  const t0 = Date.now();
  const w = aiSandbox(seed);
  const rows: RealmRow[] = realmRows(w);
  const audit = runAudited(w, days, (world, a) => {
    if (a.days % 90 === 0) rows.push(...realmRows(world));
  });
  const journal = aiJournal().slice();
  const seconds = (Date.now() - t0) / 1000;
  const base = { seed, days, seconds, audit, journal, rows, world: w };
  const markdown = narrative(base);
  // The save: the realm the sandbox names as the player's takes the throne again (the world scene needs a player).
  for (const e of Object.values(w.engagements)) if (e.status === 'pending_player') e.status = 'auto';
  w.factions[w.playerFactionId]!.isPlayer = true;
  w.events.pending = w.events.pending.filter((p) => p.scope.factionId !== w.playerFactionId);
  const meta: SaveGame['meta'] = {
    slot: 'sim02',
    name: `SIM-02 AI year (seed ${seed})`,
    mode: 'sandbox',
    scene: 'world',
    playerFactionId: w.playerFactionId,
    calendar: { ...w.calendar },
    createdAt: '2026-10-30T00:00:00.000Z',
    playtimeSec: 0,
    buildVersion: 'sim-02',
    summary: `AI-only sandbox after ${days} days`,
    thumbnail: null,
  };
  const game: SaveGame = { format: 'samrajya-save', version: SAVE_VERSION, meta, session: { mode: 'sandbox', scene: 'world', skirmish: null, activeEngagementId: null, hero: null }, world: w, battle: null };
  const saveText = serializeSave(game);
  return { ...base, markdown, saveText, saveIndex: { sim02: { meta, sizeBytes: saveText.length } } };
}
