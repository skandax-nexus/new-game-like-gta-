/**
 * Siege AI report (SIM-02 rework round 1 evidence; OWNER: AI Engineer - Battle AI, Intents & Campaign AI): every
 * harness/sieges.ts variant AI against AI over a few seeds, the summary table, and one battle's full plan log and
 * 60-second timeline. Used by scripts/sim-ai/sieges.mjs -> docs/sprint1/sim-02/sieges.md.
 */
import { battlePlanLog, resetBattlePlanLog } from '../../../../src/sim/tactical/ai/common';
import type { SiegeSummary, SiegeVariant } from './sieges';
import { SIEGE_VARIANTS, siegeBattle, summarize } from './sieges';

const m = (x: number | null): string => (x === null ? '-' : `${(x / 60).toFixed(1)}`);

export function siegeReport(seeds: number, traceVariant: SiegeVariant = 'engineers'): { markdown: string; rows: { variant: SiegeVariant; seed: number; s: SiegeSummary }[] } {
  const rows: { variant: SiegeVariant; seed: number; s: SiegeSummary }[] = [];
  let trace: string[] = [];
  let plan: string[] = [];
  for (const v of SIEGE_VARIANTS) {
    for (let seed = 1; seed <= seeds; seed++) {
      resetBattlePlanLog();
      const lines: string[] = [];
      const b = siegeBattle(v, { seed });
      const s = summarize(b, 1800, v === traceVariant && seed === 1 ? (l) => lines.push(l) : undefined, 60);
      rows.push({ variant: v, seed, s });
      if (v === traceVariant && seed === 1) {
        trace = lines;
        plan = battlePlanLog()
          .filter((e) => e.side === 0)
          .map((e) => `${(e.time / 60).toFixed(2)} min  ${e.text}`);
      }
    }
  }
  const md: string[] = [];
  md.push('# Siege battle AI - AI against AI (SIM-02 rework round 1)');
  md.push('');
  md.push('Generated by `node scripts/sim-ai/sieges.mjs` from `tests/sim/ai/harness/sieges.ts` (the scenarios of the');
  md.push('siege-watch tool): a town of radius 120 m (fort level 2: 2 gates of 251 HP, 12 towers) held by 2 archer + 2 spear');
  md.push('formations and engineers (AI); the besiegers (AI) come from +Z with 3 spears, 2 archers, 1 horse and');
  md.push('`engineers`: 2 engineer formations / `elephants`: 1 engineer formation + war elephants / `ram_only`: 1 engineer formation.');
  md.push('Times in minutes of battle time. "Archer stand-off" = least distance between an attacking archer formation and a wall');
  md.push('archer with arrows before the ram was committed (wall reach is 192 m on the walls, 230 m from a tower).');
  md.push('');
  md.push('| Variant | Seed | Outcome | Min | Withdrawal reason | Ram built | Ram at gate | Gate broken | Breach held from | Palisades | Archer stand-off (m) | Towers manned | Stormer jam (s) | Losses att / def |');
  md.push('|---|---|---|---|---|---|---|---|---|---|---|---|---|---|');
  for (const r of rows) {
    const s = r.s;
    md.push(`| ${r.variant} | ${r.seed} | ${s.outcome} (side ${s.winner}) | ${s.minutes.toFixed(1)} | ${s.withdrawReason ?? '-'} | ${m(s.ramBuilt)} | ${m(s.ramAtGate)} | ${m(s.gateBroken)} | ${m(s.breachHoldSince)} | ${s.palisades} | ${Number.isFinite(s.archerExposure) ? s.archerExposure.toFixed(0) : '-'} | ${s.maxTowersManned} | ${s.stormerJam.toFixed(0)} | ${s.losses.join(' / ')} |`);
  }
  md.push('');
  md.push(`## Plan log of \`${traceVariant}\` seed 1 (attacker, \`battlePlanLog()\`)`);
  md.push('');
  md.push('```');
  for (const l of plan) md.push(l);
  md.push('```');
  md.push('');
  md.push(`## Timeline of \`${traceVariant}\` seed 1 (every 60 s: plan phase, gates, towers, works, every formation)`);
  md.push('');
  md.push('Formation: index, class + side, position, shape, order, activity, soldiers, morale, arrows.');
  md.push('');
  md.push('```');
  for (const l of trace) md.push(l);
  md.push('```');
  md.push('');
  return { markdown: md.join('\n'), rows };
}
